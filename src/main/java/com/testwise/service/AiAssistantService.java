package com.testwise.service;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import java.net.URI;
import java.net.http.*;
import java.time.Duration;
import java.util.regex.*;

@Service
public class AiAssistantService {
    @Value("${testwise.ai.api-url:}") private String apiUrl;
    @Value("${testwise.ai.api-key:}") private String apiKey;
    @Value("${testwise.ai.model:gpt-4o-mini}") private String model;

    public String generateTestCases(String requirement) {
        String prompt = "Act as a careful QA engineer. Create 5 concise test cases for this software requirement: "
                + requirement + ". Include positive, negative, boundary cases. Return numbered cases with title, steps, and expected result. Do not claim tests were executed.";
        String remote = callCompatibleApi(prompt);
        if (remote != null) return remote;
        return localTestSuggestions(requirement);
    }

    public String analyzeBug(String title, String description, String expected, String actual) {
        String prompt = "Act as a QA assistant. Analyze this bug report. Give possible causes (not confirmed facts), next debugging steps, and useful regression tests. "
                + "Title: " + title + "; Description: " + description + "; Expected: " + expected + "; Actual: " + actual;
        String remote = callCompatibleApi(prompt);
        if (remote != null) return remote;
        return "AI analysis (local fallback; configure an LLM API for model-generated analysis):\n"
                + "• Verify the issue is reproducible and record browser/device, input data, and timestamp.\n"
                + "• Compare actual and expected results; inspect browser console, server logs, and API responses.\n"
                + "• Possible cause: validation, state handling, network/API response, or an unhandled edge case. These are hypotheses, not confirmed root causes.\n"
                + "• Regression checks: repeat the exact steps, test valid/invalid inputs, refresh/re-login if relevant, and verify adjacent workflows.\n"
                + "Reported actual result: " + (actual == null || actual.isBlank() ? description : actual);
    }

    private String callCompatibleApi(String prompt) {
        if (apiUrl == null || apiUrl.isBlank() || apiKey == null || apiKey.isBlank()) return null;
        try {
            String body = "{\"model\":\"" + escape(model) + "\",\"messages\":[{\"role\":\"user\",\"content\":\"" + escape(prompt) + "\"}],\"temperature\":0.2}";
            HttpRequest request = HttpRequest.newBuilder(URI.create(apiUrl))
                    .timeout(Duration.ofSeconds(25))
                    .header("Content-Type", "application/json")
                    .header("Authorization", "Bearer " + apiKey)
                    .POST(HttpRequest.BodyPublishers.ofString(body)).build();
            HttpResponse<String> response = HttpClient.newHttpClient().send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() < 200 || response.statusCode() >= 300) return null;
            Matcher m = Pattern.compile("\"content\"\\s*:\\s*\"((?:\\\\.|[^\"\\\\])*)\"").matcher(response.body());
            if (!m.find()) return null;
            return m.group(1).replace("\\n", "\n").replace("\\\"","\"").replace("\\\\","\\");
        } catch (Exception ex) {
            return null; // Keep core features usable if the optional AI provider is unavailable.
        }
    }

    private String localTestSuggestions(String requirement) {
        return "AI test suggestions (rule-based fallback; not generated by an LLM) for: " + requirement + "\n\n"
          + "1. Positive test: provide valid inputs and verify the requirement succeeds.\n"
          + "2. Negative test: omit a required field and verify a clear validation message appears.\n"
          + "3. Invalid-data test: provide malformed or unsupported input and verify it is safely rejected.\n"
          + "4. Boundary test: test minimum/maximum allowed values and values just outside the limits.\n"
          + "5. State/repeat test: repeat the action and refresh/reopen the page to verify data remains consistent.\n\n"
          + "Review and adapt these suggestions before execution.";
    }
    private String escape(String s) {
        if (s == null) return "";
        return s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t");
    }
}
